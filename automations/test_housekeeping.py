def tokens(lb):
    f = lb.fields
    return {
        "ST": f["status"], "OWNER": f["owner"], "TOPIC": f["topic"], "LINEAR": f["linear"],
        "DEADLINE": f["deadline"], "CREATED": f["created"], "UPDATED": f["updated"],
        "NONE": lb.none, "OPEN": lb.statuses["open"], "CLOSED": lb.statuses["closed"],
        "OBSOLETE": lb.statuses["obsolete"], "STATE": lb.state_line, "NEXT": lb.next_step_line,
        "SEC_OPEN": lb.sections["open"], "SEC_REC": lb.sections["recurring"], "SEC_CAND": lb.sections["candidates"],
        "CAND": lb.candidate_type, "CARD_STATE": lb.card_state_heading, "CARD_HIST": lb.card_history_heading,
        "FOOTER": lb.history_footer, "SRC": lb.source_marker,
        "EV_CREATED": lb.events["created"], "EV_TYPE": lb.events["type"], "EV_OBSOLETE": lb.events["obsolete"],
    }


