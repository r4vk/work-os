@for_each_label_set
class Apply(Base):
    def test_rollover_moves_log_and_history(self):
        root = self.make_vault()
        ops = hk.apply(root, date(2027, 1, 2), labels=self.LABELS)
        hist = root / "topics/domains/example"
        self.assertTrue((root / "archive/tasks/TASKS-log-2026-Q4.md").exists())
        self.assertTrue((hist / "example-topic-history-2026-Q4.md").exists())
        live_log, _ = hk.parse_front_matter((root / "TASKS-log.md").read_text(encoding="utf-8"))
        live_hist, _ = hk.parse_front_matter((hist / "example-topic-history.md").read_text(encoding="utf-8"))
        self.assertEqual(live_log["period"], "2027-Q1")
        self.assertEqual(live_hist["previous"], ["example-topic-history-2026-Q3", "example-topic-history-2026-Q4"])
        self.assertTrue(any("rollover" in o for o in ops))

    def test_archives_closed_record_and_keeps_open(self):
        closed = self.GOOD.replace(self.L("- {ST}: {OPEN} · {OWNER}: Alex [OPS]"), self.L("- {ST}: {CLOSED} · {OWNER}: Alex [OPS]"))
        root = self.make_vault(tasks=closed)
        hk.apply(root, date(2026, 10, 5), labels=self.LABELS)
        tasks = (root / "TASKS.md").read_text(encoding="utf-8")
        arch = (root / "archive/tasks/TASKS-2026-Q4.md").read_text(encoding="utf-8")
        self.assertNotIn("T-20260922-01", tasks)
        self.assertIn("### T-20260922-01 · WAITING_FOR_OTHER", arch)
        self.assertIn(self.L("- {ST}: {CLOSED}"), arch)
        self.assertIn("T-20260929-03", tasks)
        recs, viol = self.parse(tasks)
        self.assertEqual(viol, [])
        self.assertEqual(len(recs), 2)

    def test_expires_stale_candidate_with_log_line(self):
        root = self.make_vault()
        hk.apply(root, date(2026, 10, 20), labels=self.LABELS)
        tasks = (root / "TASKS.md").read_text(encoding="utf-8")
        log = (root / "TASKS-log.md").read_text(encoding="utf-8")
        arch = (root / "archive/tasks/TASKS-2026-Q4.md").read_text(encoding="utf-8")
        self.assertNotIn("T-20260930-01", tasks)
        self.assertIn(self.L("- {ST}: {OBSOLETE} · {OWNER}: Alex [TEAM]"), arch)
        reason = self.LABELS.msg("expire_reason", days=14)
        self.assertIn(self.L("· T-20260930-01 · {EV_OBSOLETE}: ") + reason, log)

    def test_apply_is_idempotent(self):
        root = self.make_vault()
        hk.apply(root, date(2026, 10, 20), labels=self.LABELS)
        self.assertEqual(hk.apply(root, date(2026, 10, 20), labels=self.LABELS), [])


