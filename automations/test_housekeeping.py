def for_each_label_set(mixin):
    """Generate <Mixin>En and <Mixin>Pl TestCase classes running the mixin for each built-in label set."""
    for suffix, lb in (("En", hk.EN), ("Pl", hk.PL)):
        name = f"{mixin.__name__}{suffix}"
        globals()[name] = type(name, (mixin, unittest.TestCase), {"LABELS": lb})
    return mixin


class Base:
    LABELS = hk.EN

    def L(self, s):
        return s.format(**tokens(self.LABELS))

    @property
    def GOOD(self):
        return self.L(TASKS_TPL)

    @property
    def CARD_GOOD(self):
        return self.L(CARD_TPL)

    @property
    def HIST_GOOD(self):
        return self.L(HIST_TPL)

    @property
    def LOG_GOOD(self):
        return self.L(LOG_TPL)

    def parse(self, text):
        return hk.parse_tasks(text, labels=self.LABELS)

    def check(self, text, today=date(2026, 9, 30)):
        recs, _ = self.parse(text)
        return [v.code for v in hk.check_tasks(recs, today, labels=self.LABELS)]

    def make_vault(self, tasks=None, log=None, hist=None):
        root = build_vault(self.LABELS, tasks, log, hist)
        self.addCleanup(shutil.rmtree, root, True)
        return root


def build_vault(lb, tasks=None, log=None, hist=None):
    """Temporary vault with TASKS.md, TASKS-log.md, one card and its history rendered in label set `lb`."""
    render = lambda s: s.format(**tokens(lb))
    root = Path(tempfile.mkdtemp())
    (root / "archive" / "tasks").mkdir(parents=True)
    (root / "topics" / "domains" / "example").mkdir(parents=True)
    (root / "TASKS.md").write_text(tasks if tasks is not None else render(TASKS_TPL), encoding="utf-8")
    (root / "TASKS-log.md").write_text(log if log is not None else render(LOG_TPL), encoding="utf-8")
    (root / "topics/domains/example/example-topic.md").write_text(render(CARD_TPL), encoding="utf-8")
    (root / "topics/domains/example/example-topic-history.md").write_text(
        hist if hist is not None else render(HIST_TPL), encoding="utf-8")
    return root


@for_each_label_set
class ParseTasks(Base):
    def test_parses_three_records_without_violations(self):
        recs, viol = self.parse(self.GOOD)
        self.assertEqual(viol, [])
        self.assertEqual([r.id for r in recs], ["T-20260929-03", "T-20260922-01", "T-20260930-01"])
        r = recs[0]
        lb = self.LABELS
        self.assertEqual((r.typ, r.status, r.linear, r.deadline), ("ACTION_REQUIRED", lb.statuses["open"], lb.none, lb.none))
        self.assertEqual(r.topic, "example-topic")
        self.assertEqual(r.next_step, "forward the date to finance.")
        self.assertEqual(r.section, lb.sections["open"])
        self.assertEqual(recs[2].section, lb.sections["candidates"])

    def test_header_without_id_is_violation(self):
        bad = self.GOOD.replace("### T-20260922-01 · WAITING_FOR_OTHER · ", "### [ACTION_REQUIRED — NEW 2026-09-22] ")
        _, viol = self.parse(bad)
        self.assertEqual([v.code for v in viol], ["HEADER_FORMAT"])

    def test_wrong_field_order_is_violation(self):
        bad = self.GOOD.replace(self.L("- {ST}: {OPEN} · {OWNER}: Alex [TEAM] · {TOPIC}: [[example-topic]] · {LINEAR}: {NONE} · {DEADLINE}: {NONE} · {CREATED}: 2026-09-29"),
                                self.L("- {OWNER}: Alex [TEAM] · {ST}: {OPEN} · {TOPIC}: [[example-topic]] · {LINEAR}: {NONE} · {DEADLINE}: {NONE} · {CREATED}: 2026-09-29"))
        _, viol = self.parse(bad)
        self.assertIn("FIELDS_FORMAT", [v.code for v in viol])

    def test_extra_line_in_record_is_violation(self):
        nxt = self.L("- {NEXT}: forward the date to finance.\n")
        bad = self.GOOD.replace(nxt, nxt + "> **REVIEW 2026-09-30:** long comment\n")
        _, viol = self.parse(bad)
        self.assertIn("EXTRA_LINE", [v.code for v in viol])

    def test_stan_without_source_is_violation(self):
        bad = self.GOOD.replace(self.L("- {STATE}: returned, waiting for Sam. ({SRC}: Mail 1a0e, 2026-09-28)"),
                                self.L("- {STATE}: returned, waiting for Sam."))
        _, viol = self.parse(bad)
        self.assertIn("STAN_NO_SOURCE", [v.code for v in viol])


