class LabelSelection(unittest.TestCase):
    def vault(self, labels_json=None):
        root = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, root, True)
        (root / "automations").mkdir()
        if labels_json is not None:
            (root / "automations" / "housekeeping.labels.json").write_text(json.dumps(labels_json), encoding="utf-8")
        return root

    def run_main(self, argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = hk.main(argv)
        return code, out.getvalue(), err.getvalue()

    def test_default_is_en(self):
        self.assertEqual(hk.resolve_labels(None, self.vault()).fields["created"], "Created")

    def test_vault_file_selects_base(self):
        self.assertEqual(hk.resolve_labels(None, self.vault({"base": "pl"})).fields["created"], "Utworzono")

    def test_vault_file_without_base_defaults_to_en(self):
        lb = hk.resolve_labels(None, self.vault({"none": "n/a"}))
        self.assertEqual((lb.none, lb.fields["topic"]), ("n/a", "Topic"))

    def test_cli_overrides_vault_file(self):
        self.assertEqual(hk.resolve_labels("en", self.vault({"base": "pl"})).state_line, "State")
        self.assertEqual(hk.resolve_labels("pl", self.vault()).state_line, "Stan")

    def test_cli_path_to_json(self):
        root = self.vault()
        p = root / "my-labels.json"
        p.write_text(json.dumps({"base": "pl", "state_line": "Status bieżący"}), encoding="utf-8")
        lb = hk.resolve_labels(str(p), root)
        self.assertEqual((lb.state_line, lb.fields["topic"]), ("Status bieżący", "Temat"))

    def test_overrides_merge_nested_keys(self):
        lb = hk.resolve_labels(None, self.vault({"base": "en", "fields": {"linear": "Jira"},
                                                 "sections": {"candidates": "Potential tasks"},
                                                 "_comment": "ignored"}))
        self.assertEqual((lb.fields["linear"], lb.fields["status"]), ("Jira", "Status"))
        text = EN_LITERAL.replace("Linear:", "Jira:").replace("## Candidates", "## Potential tasks")
        recs, viol = hk.parse_tasks(text, labels=lb)
        self.assertEqual(viol, [])
        self.assertEqual(recs[1].section, "Potential tasks")

    def test_unknown_label_set_is_clear_error(self):
        with self.assertRaises(hk.LabelError) as cm:
            hk.resolve_labels("de", self.vault())
        self.assertIn("unknown label set 'de'", str(cm.exception))
        self.assertIn("en, pl", str(cm.exception))

    def test_missing_json_file_is_error(self):
        with self.assertRaises(hk.LabelError) as cm:
            hk.load_labels("/nonexistent/labels.json")
        self.assertIn("not found", str(cm.exception))

    def test_unknown_key_unknown_subkey_unknown_base_bad_json(self):
        for bad in ({"colour": "x"}, {"fields": {"prio": "P"}}, {"base": "fr"}, {"types": "FYI"}):
            with self.subTest(bad=bad), self.assertRaises(hk.LabelError):
                hk.resolve_labels(None, self.vault(bad))
        root = self.vault()
        (root / "automations" / "housekeeping.labels.json").write_text("{not json", encoding="utf-8")
        with self.assertRaises(hk.LabelError) as cm:
            hk.resolve_labels(None, root)
